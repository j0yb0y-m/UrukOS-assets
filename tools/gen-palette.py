#!/usr/bin/env python3
"""Generate every UrukOS theme file from brand/palette.json.

Usage:
    python3 tools/gen-palette.py          regenerate all theme files
    python3 tools/gen-palette.py --check  verify files are in sync (exit 1 if not)

Never hand-edit a theme file; edit brand/palette.json and re-run this script.
"""

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PALETTE_PATH = ROOT / "brand" / "palette.json"


def load_palette() -> dict:
    with PALETTE_PATH.open(encoding="utf-8") as fh:
        return json.load(fh)


def C(p: dict, key: str) -> str:
    return p["colors"][key]["hex"]


def ANSI(p: dict) -> dict:
    a = p["ansi"]
    return {
        "black": a["black"],
        "red": a["red"],
        "green": a["green"],
        "yellow": a["yellow"],
        "blue": a["blue"],
        "magenta": a["magenta"],
        "cyan": a["cyan"],
        "white": a["white"],
        "bright_black": a["bright_black"],
        "bright_red": a["bright_red"],
        "bright_green": a["bright_green"],
        "bright_yellow": a["bright_yellow"],
        "bright_blue": a["bright_blue"],
        "bright_magenta": a["bright_magenta"],
        "bright_cyan": a["bright_cyan"],
        "bright_white": a["bright_white"],
    }


def ghostty_theme(p: dict) -> str:
    a = ANSI(p)
    keys = ["black", "red", "green", "yellow", "blue", "magenta", "cyan", "white"]
    lines = [
        "# UrukOS Ghostty theme - GENERATED by tools/gen-palette.py, do not edit",
        f"background = {C(p, 'bg')}",
        f"foreground = {C(p, 'fg')}",
        f"cursor-color = {C(p, 'accent')}",
        f"selection-background = {C(p, 'accent2')}",
        f"selection-foreground = {C(p, 'fg')}",
    ]
    for i, k in enumerate(keys):
        lines.append(f"palette = {i}={a[k]}")
    for i, k in enumerate(keys):
        lines.append(f"palette = {i + 8}={a['bright_' + k]}")
    return "\n".join(lines) + "\n"


