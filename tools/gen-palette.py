def plymouth_script(p: dict) -> str:
    def f(key: str) -> tuple:
        h = C(p, key).lstrip("#")
        return (int(h[0:2], 16) / 255, int(h[2:4], 16) / 255, int(h[4:6], 16) / 255)

    bg = f("bg")
    surface = f("surface")
    return f"""// UrukOS Plymouth script - GENERATED by tools/gen-palette.py, do not edit
Window.SetBackgroundTopColor({bg[0]:.3f}, {bg[1]:.3f}, {bg[2]:.3f});
Window.SetBackgroundBottomColor({surface[0]:.3f}, {surface[1]:.3f}, {surface[2]:.3f});

logo.image = Image("watermark.png");
logo.sprite = Sprite(logo.image);
logo.sprite.SetX(Window.GetWidth() / 2 - logo.image.GetWidth() / 2);
logo.sprite.SetY(Window.GetHeight() / 2 - logo.image.GetHeight() / 2 - 40);

message_sprite = Sprite();

fun refresh_callback () {{
    if (progress_bar) {{
        progress_bar.sprite.SetX(Window.GetWidth() / 2 - progress_bar.image.GetWidth() / 2);
    }}
}}
Plymouth.SetRefreshFunction(refresh_callback);

fun message_callback (text) {{
    my_image = Image.Text(text, 0.99, 0.95, 0.90);
    message_sprite.SetImage(my_image);
    message_sprite.SetX(Window.GetWidth() / 2 - my_image.GetWidth() / 2);
    message_sprite.SetY(Window.GetHeight() / 2 + 80);
}}
Plymouth.SetMessageFunction(message_callback);
"""


TEMPLATES = {
    "terminal/ghostty/urukos": ghostty_theme,
    "terminal/fish/urukos.theme": fish_theme,
    "terminal/tmux/urukos.conf": tmux_conf,
    "terminal/bat/themes/urukos.tmTheme": bat_theme,
    "terminal/eza/theme.yml": eza_theme,
    "terminal/fastfetch/config.jsonc": fastfetch_config,
    "kde/colors/UrukOS.colors": kde_colors,
    "kde/look-and-feel/org.urukos.desktop/contents/defaults": kde_defaults,
    "plymouth/urukos/urukos.script": plymouth_script,
}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument(
        "--check", action="store_true", help="verify generated files are in sync"
    )
    args = ap.parse_args()

    palette = load_palette()
    stale = []
    for rel, fn in TEMPLATES.items():
        expected = fn(palette)
        path = ROOT / rel
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != expected:
                stale.append(rel)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected, encoding="utf-8")
            print(f"wrote {rel}")
    if args.check:
        if stale:
            print("STALE: " + ", ".join(stale))
            return 1
        print("OK: all theme files in sync with brand/palette.json")
        return 0
    return 0


if __name__ == "__main__":
    sys.exit(main())
